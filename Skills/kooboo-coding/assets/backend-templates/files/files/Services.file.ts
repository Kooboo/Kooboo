/* kooboo-app-base:v2; object-type: CodeBlock */
import { ENV } from './ENV'

export interface StoredFile {
  fileKey: string
  state: 'temporary' | 'permanent'
  path: string
  url: string
  size: number
  lastModified: string
}

export interface TemporaryUploadOptions {
  maxBytes?: number
  allowedExtensions?: readonly string[]
}

export interface TemporaryCleanupOptions {
  retentionHours?: number
  batchSize?: number
  afterKey?: string | null
}

const temporaryFolder = 'app-files/tmp'
const permanentFolder = 'app-files/data'
const keyPattern = /^[a-f0-9]{32}\.[a-z0-9]+$/

/** Reject paths and URLs; callers pass only keys generated by saveTemporary. */
function validateKey(fileKey: string) {
  if (typeof fileKey !== 'string' || !keyPattern.test(fileKey)) throw new Error('Invalid file key')
}

/** Read shared configuration without altering application-owned settings. */
function settings() {
  const config = ENV.files
  if (!config) throw new Error('Configure ENV.files before using file helpers')
  return config
}

/** Return one file's metadata without reading its binary content. */
function describe(fileKey: string, state: 'temporary' | 'permanent'): StoredFile | null {
  const folder = state === 'temporary' ? temporaryFolder : permanentFolder
  const path = `${folder}/${fileKey}`
  const info = k.file.get(path)
  if (!info) return null

  return {
    fileKey, state, path, url: info.url, size: Number(info.size),
    lastModified: new Date(info.lastModified).toISOString()
  }
}

/**
 * Validate and save one upload under a new key in the temporary directory.
 * Server-selected options override ENV defaults per field without changing ENV.
 * Never pass client-supplied limits or allowlists directly as these options.
 * Authentication, ownership, quotas and mock handling belong to the caller.
 * A failed write may leave a partial temporary file, reclaimable by cleanupTemporary.
 */
export function saveTemporary(file: { fileName: string; bytes: number[] }, options: TemporaryUploadOptions = {}): StoredFile {
  const config = settings()
  if (!options || typeof options !== 'object' || Array.isArray(options)) throw new Error('Invalid upload options')
  const maxBytes = options.maxBytes === undefined ? config.maxBytes : options.maxBytes
  const extensions = options.allowedExtensions === undefined ? config.allowedExtensions : options.allowedExtensions
  if (!Number.isSafeInteger(maxBytes) || maxBytes <= 0 ||
      !Array.isArray(extensions) || !extensions.length ||
      extensions.some(value => typeof value !== 'string' || !/^[a-z0-9]+$/i.test(value))) {
    throw new Error('Invalid upload configuration')
  }
  const allowedExtensions = extensions.map(value => value.toLowerCase())

  const name = String(file.fileName || '').split(/[\\/]/).pop() || ''
  const extension = name.includes('.') ? name.split('.').pop()!.toLowerCase() : ''
  if (!name || name.length > 200 || /[\x00-\x1f\x7f]/.test(name) ||
      !/^[a-z0-9]+$/.test(extension) || !allowedExtensions.includes(extension)) {
    throw new Error('Unsupported file name or extension')
  }

  const bytes = file.bytes
  if (!bytes || !bytes.length || bytes.length > maxBytes) throw new Error('File is empty or exceeds the size limit')

  const fileKey = `${String(k.security.newGuid()).toLowerCase()}.${extension}`
  validateKey(fileKey)
  const path = `${temporaryFolder}/${fileKey}`
  if (k.file.exists(path) || k.file.exists(`${permanentFolder}/${fileKey}`)) throw new Error('File key already exists')

  const written = k.file.writeBinary(path, bytes)
  if (!written) throw new Error('File write failed')
  const result = describe(fileKey, 'temporary')
  if (!result) throw new Error('Saved file could not be read')
  return result
}

/**
 * Move a temporary file into permanent storage, preserving its key.
 * Repeated promotion returns the existing permanent file without overwriting it.
 * The caller coordinates business persistence and compensation for failed saves.
 */
export function promoteFile(fileKey: string): StoredFile {
  validateKey(fileKey)
  const existing = describe(fileKey, 'permanent')
  if (existing) return existing

  const source = `${temporaryFolder}/${fileKey}`
  const destination = `${permanentFolder}/${fileKey}`
  if (!k.file.exists(source)) throw new Error('Temporary file not found')

  try {
    k.file.rename(source, destination)
  } catch (error) {
    // Another promotion may have completed after the initial existence check.
    const promoted = describe(fileKey, 'permanent')
    if (promoted && !k.file.exists(source)) return promoted
    throw error
  }

  const result = describe(fileKey, 'permanent')
  if (!result) throw new Error('Promoted file could not be read')
  return result
}

/** Resolve a managed key, preferring permanent storage; return null when absent. */
export function getFile(fileKey: string): StoredFile | null {
  validateKey(fileKey)
  return describe(fileKey, 'permanent') || describe(fileKey, 'temporary')
}

/**
 * Explicitly delete both managed locations for a key; missing files are harmless.
 * The caller must authorize deletion and confirm no business records still use it.
 * Coordinate concurrent saves before calling; this helper does not lock business data.
 */
export function deleteFile(fileKey: string) {
  validateKey(fileKey)
  k.file.delete(`${temporaryFolder}/${fileKey}`)
  k.file.delete(`${permanentFolder}/${fileKey}`)
}

/**
 * Inspect one batch of temporary keys and remove files older than the retention period.
 * Pass nextCursor as afterKey to continue; begin a later sweep without a cursor.
 * Failures remain on disk and are returned for retry on a later sweep.
 * FileIO enumerates the folder eagerly; batchSize bounds inspections/deletion attempts,
 * not the underlying directory enumeration. This never scans permanent storage.
 */
export function cleanupTemporary(options: TemporaryCleanupOptions = {}) {
  const config = settings()
  const retentionHours = options.retentionHours ?? config.temporaryHours
  const batchSize = options.batchSize ?? config.cleanupBatchSize
  const afterKey = options.afterKey ?? null
  if (!Number.isFinite(retentionHours) || retentionHours <= 0 ||
      !Number.isSafeInteger(batchSize) || batchSize <= 0) throw new Error('Invalid cleanup options')
  if (afterKey !== null) validateKey(afterKey)

  const cutoff = Date.now() - retentionHours * 3600000
  const keys = k.file.folderFiles(temporaryFolder)
    .map(file => file.name)
    .filter(key => keyPattern.test(key) && (afterKey === null || key > afterKey))
    .sort()
  const batch = keys.slice(0, batchSize)
  let deleted = 0
  let skipped = 0
  const failures: { fileKey: string; message: string }[] = []

  for (const fileKey of batch) {
    try {
      // Re-read because promotion or another cleanup may have changed the directory.
      const file = describe(fileKey, 'temporary')
      if (!file || new Date(file.lastModified).getTime() > cutoff) {
        skipped++
        continue
      }
      k.file.delete(file.path)
      deleted++
    } catch (error) {
      failures.push({ fileKey, message: error instanceof Error ? error.message : String(error) })
    }
  }

  return {
    inspected: batch.length, deleted, skipped, failures,
    nextCursor: keys.length > batch.length ? batch[batch.length - 1] : null
  }
}
